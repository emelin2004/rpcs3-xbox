#!/usr/bin/env python3
"""Builds the UWP English string table from rpcs3qt/localized_emu.h.

The Qt UI translates emulator strings (home menu, dialogs, trophies) through Qt's tr().
The UWP build has no Qt, so this pulls the English source strings out of the same switch
and writes them as X(id, has_arg, "text") lines for uwp_localized.cpp.
"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]

case_re = re.compile(r'^\s*case localized_string_id::(\w+):\s*return\s+(.*);\s*$')
literal_re = re.compile(r'"((?:[^"\\]|\\.)*)"')

entries = []
with open(src, encoding='utf-8') as f:
    for line in f:
        m = case_re.match(line)
        if not m:
            continue
        name, expr = m.groups()
        if expr == '""':
            entries.append((name, False, ''))
            continue
        if not expr.startswith('tr('):
            sys.exit(f'gen_localized.py: unexpected expression for {name}: {expr}')
        lit = literal_re.search(expr)
        if not lit:
            sys.exit(f'gen_localized.py: no string literal for {name}')
        entries.append((name, '.arg(' in expr, lit.group(1)))

if len(entries) < 100:
    sys.exit(f'gen_localized.py: only {len(entries)} strings found in {src}; did the format change?')

with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by uwp/app/gen_localized.py from rpcs3qt/localized_emu.h. Do not edit.\n')
    for name, has_arg, text in entries:
        f.write(f'X({name}, {"true" if has_arg else "false"}, u8"{text}")\n')
